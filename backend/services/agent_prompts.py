def build_time_block(round_to_minutes: int = 5) -> str:
    """
    Динамический блок с текущим временем (МСК + UTC) и правилами работы со
    временем. Пересобирается при каждом вызове, поэтому время всегда актуально.
    Сервер хранит время в UTC, а пользователю показываем МСК (UTC+3).

    round_to_minutes > 1 — время округляется ВНИЗ с этим шагом: кэширование
    промпта у провайдеров (OpenRouter → OpenAI/DeepSeek/Anthropic/Gemini)
    требует побайтового совпадения префикса запроса, и время с точностью до
    минуты ломало кэш на каждом запросе. Внутри окна округления все запросы
    получают идентичный блок времени.

    round_to_minutes = 0 — точное время до минуты, без пометки об округлении.
    Использовать, когда блок приклеивается к user-сообщению и кэш префикса
    не страдает.
    """
    msk = now_msk()
    utc = now_utc()
    rounding_note = ""
    if round_to_minutes and round_to_minutes > 1:
        msk = msk.replace(minute=msk.minute - msk.minute % round_to_minutes, second=0, microsecond=0)
        utc = utc.replace(minute=utc.minute - utc.minute % round_to_minutes, second=0, microsecond=0)
        rounding_note = f", время округлено вниз с шагом {round_to_minutes} мин"
    weekday = _WEEKDAYS_RU[msk.weekday()]
    return f"""

# ТЕКУЩЕЕ ВРЕМЯ
- Сейчас по МСК (UTC+3): {msk.strftime('%Y-%m-%d %H:%M')} ({weekday}){rounding_note}
- Сейчас по UTC: {utc.strftime('%Y-%m-%d %H:%M')}

# ПРАВИЛА РАБОТЫ СО ВРЕМЕНЕМ (ОБЯЗАТЕЛЬНО)
- Пользователю ВСЕГДА показывай дату и время по МСК и помечай «(МСК)».
- Tools и история звонков возвращают время в UTC. Перед тем как назвать его
  пользователю — переведи в МСК (прибавь 3 часа) и укажи «(МСК)».
- Время, которое называет пользователь, — это всегда МСК.
- Если просят позвонить «через N минут/часов» — передавай в create_agent_task
  параметр delay_minutes (сервер сам вычислит точное время от текущего
  момента). scheduled_at в этом случае НЕ передавай и НЕ вычисляй сам.
- Абсолютное время («завтра в 14:00») — поле scheduled_at в UTC, в формате
  ISO 8601 с «Z» (например 2026-06-09T12:00:00Z). Чтобы получить UTC из
  названного пользователем времени по МСК — вычти 3 часа.
- Никогда не показывай пользователю «сырое» UTC-время."""


def build_knowledge_base_block(agent_config) -> str:
    """
    Блок про векторную базу знаний. Добавляется только если у агента
    создана база (есть kb_namespace). Подсказывает оркестратору вызывать
    search_knowledge_base для фактических вопросов.
    """
    if not getattr(agent_config, "kb_namespace", None):
        return ""
    kb_name = getattr(agent_config, "kb_name", None) or "база знаний компании"
    return f"""

# БАЗА ЗНАНИЙ
У владельца загружена векторная база знаний («{kb_name}»). Когда нужен
фактический ответ по продукту, услугам, ценам, условиям или другим деталям из
материалов компании — вызывай инструмент search_knowledge_base с поисковым
запросом. Не выдумывай факты: если ответа нет в результатах поиска — скажи об
этом прямо."""


def build_webhook_block(agent_config) -> str:
    """
    Блок про вебхук. Добавляется только если у агента задан webhook_url.
    Показывает URL и подсказывает оркестратору вызывать send_webhook, когда нужно
    передать данные/событие во внешнюю систему.
    """
    url = (getattr(agent_config, "webhook_url", None) or "").strip()
    if not url:
        return ""
    return f"""

# ВЕБХУК (отправка событий во внешнюю систему)
У владельца настроен вебхук: {url}
Когда по итогу разговора или сообщения нужно передать данные во внешнюю систему
(заявка, бронирование, лид, важное событие или результат звонка) — вызывай
инструмент send_webhook. URL подставляется автоматически, передавать его не нужно:
укажи только event (код события) и payload (данные). Не вызывай вебхук без причины
и не дублируй одно и то же событие."""


def build_orchestrator_prompt(agent_config, include_time_block: bool = True) -> str:
    """
    Собирает финальный промпт оркестратора из шаблона + данных агента.
    Пустые поля заменяются на "(не указано)".
    К промпту добавляется блок базы знаний (если есть) и актуальный блок времени.

    include_time_block=False — для одноразовых вызовов (PreCall/PostCall):
    блок времени там переносится в user-сообщение, а системный промпт остаётся
    полностью статичным и целиком попадает в кэш провайдера.
    """
    base = ORCHESTRATOR_PROMPT_BASE.format(
        doc_who_am_i=agent_config.doc_who_am_i or "(не указано)",
        doc_who_we_call=agent_config.doc_who_we_call or "(не указано)",
        doc_how_we_talk=agent_config.doc_how_we_talk or "(не указано)",
        doc_what_we_offer=agent_config.doc_what_we_offer or "(не указано)",
        doc_rules_and_goals=agent_config.doc_rules_and_goals or "(не указано)",
        additional_instructions=agent_config.additional_instructions or "(нет дополнительных инструкций)"
    )
    prompt = (
        base
        + build_knowledge_base_block(agent_config)
        + build_webhook_block(agent_config)
    )
    if include_time_block:
        prompt += build_time_block()
    return prompt


def get_voice_agent_prompt() -> str:
    """Возвращает базовый промпт голосового агента (без подстановок)."""
    return VOICE_AGENT_PROMPT_BASE


def build_voice_agent_prompt(voice_additional_instructions: str = None) -> str:
    """
    Собирает system_prompt голосового агента: базовый промпт + (опционально)
    дополнительные инструкции от владельца по поведению в живом звонке.
    """
    prompt = VOICE_AGENT_PROMPT_BASE
    extra = (voice_additional_instructions or "").strip()
    if extra:
        prompt += (
            "\n\n# ДОПОЛНИТЕЛЬНЫЕ ИНСТРУКЦИИ ОТ ВЛАДЕЛЬЦА\n"
            f"{extra}"
        )
    return prompt
